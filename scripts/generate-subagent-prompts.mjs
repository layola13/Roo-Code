/**
 * Generate subagent prompts TypeScript file from Markdown sources
 * 
 * This script reads .roo/agents/*.md files and embeds their content
 * into src/shared/subagent-prompts.ts for static compilation.
 */

import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)
const rootDir = path.join(__dirname, '..')

try {
	// Read MD files (skip first 6 lines - YAML frontmatter)
	const contextAnalyzer = fs.readFileSync(
		path.join(rootDir, '.roo/agents/condense-context-analyzer.md'),
		'utf8'
	).split('\n').slice(6).join('\n').trim()

	const memoryExtractor = fs.readFileSync(
		path.join(rootDir, '.roo/agents/condense-memory-extractor.md'),
		'utf8'
	).split('\n').slice(6).join('\n').trim()

	const codeSummarizer = fs.readFileSync(
		path.join(rootDir, '.roo/agents/condense-code-summarizer.md'),
		'utf8'
	).split('\n').slice(6).join('\n').trim()

	// Create TypeScript file with proper escaping for template strings
	const content = `/**
 * Default system prompts for subagents
 *
 * These prompts are statically embedded from .roo/agents/*.md files and used for both execution and UI display.
 * This ensures consistency and avoids duplication.
 * 
 * @generated This file is auto-generated by scripts/generate-subagent-prompts.mjs
 * DO NOT EDIT MANUALLY - Changes will be overwritten on next build
 */

export const DEFAULT_SUBAGENT_PROMPTS = {
	contextAnalyzer: \`${contextAnalyzer.replace(/`/g, '\\`').replace(/\${/g, '\\${')}\`,

	memoryExtractor: \`${memoryExtractor.replace(/`/g, '\\`').replace(/\${/g, '\\${')}\`,

	codeSummarizer: \`${codeSummarizer.replace(/`/g, '\\`').replace(/\${/g, '\\${')}\`,
} as const
`

	const outputPath = path.join(rootDir, 'src/shared/subagent-prompts.ts')
	fs.writeFileSync(outputPath, content)

	console.log('✅ Generated src/shared/subagent-prompts.ts')
	console.log(`   - contextAnalyzer: ${contextAnalyzer.length} chars`)
	console.log(`   - memoryExtractor: ${memoryExtractor.length} chars`)
	console.log(`   - codeSummarizer: ${codeSummarizer.length} chars`)
} catch (error) {
	console.error('❌ Failed to generate subagent prompts:', error.message)
	process.exit(1)
}